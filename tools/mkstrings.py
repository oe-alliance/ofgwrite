#!/usr/bin/env python3
# The texts of the flash window: collects them into po/ofgwrite.pot, merges that into the po/<language>.po
# files and writes i18n_strings.c from them, so ofgwrite needs no catalog files after pivot_root.
#
#   tools/mkstrings.py
import glob
import os
import re

LANGUAGES = ("de", "pl", "ar")  # The order of i18n_languages.
CALLS = re.compile(r'\b(?:set_step|set_step_without_incr|set_overall_text|N_)\(\s*"((?:[^"\\]|\\.)*)"')

os.chdir(os.path.join(os.path.dirname(__file__), ".."))


def texts():
	found = []
	for path in sorted(glob.glob("*.c")):
		if path == "i18n_strings.c":
			continue
		with open(path, encoding="utf-8") as source:
			for match in CALLS.finditer(source.read()):
				if match.group(1) and match.group(1) not in found:
					found.append(match.group(1))
	return found


def read_po(path):
	translations = {}
	if not os.path.exists(path):
		return translations
	key = None
	part = None
	entry = {}
	with open(path, encoding="utf-8") as po:
		for line in po.read().splitlines() + [""]:
			if line.startswith("msgid "):
				part, entry = "msgid", {"msgid": line[7:-1], "msgstr": ""}
			elif line.startswith("msgstr "):
				part = "msgstr"
				entry["msgstr"] = line[8:-1]
			elif line.startswith('"') and part:
				entry[part] += line[1:-1]
			elif not line.strip() and part:
				key = entry["msgid"]
				if key:
					translations[key] = entry["msgstr"]
				part = None
	return translations


def flag(text):
	return "#, c-format\n" if "%" in text else ""


def write_po(path, all_texts, translations, header):
	with open(path, "w", encoding="utf-8", newline="\n") as po:
		po.write(header)
		for text in all_texts:
			po.write('\n%smsgid "%s"\nmsgstr "%s"\n' % (flag(text), text, translations.get(text, "")))


def header(language):
	return ('msgid ""\nmsgstr ""\n"Project-Id-Version: ofgwrite\\n"\n"Language: %s\\n"\n'
		'"MIME-Version: 1.0\\n"\n"Content-Type: text/plain; charset=UTF-8\\n"\n"Content-Transfer-Encoding: 8bit\\n"\n'
		% language)


def main():
	all_texts = texts()
	os.makedirs("po", exist_ok=True)
	write_po("po/ofgwrite.pot", all_texts, {}, header(""))
	catalogs = {}
	for language in LANGUAGES:
		catalogs[language] = read_po("po/%s.po" % language)
		write_po("po/%s.po" % language, all_texts, catalogs[language], header(language))
	with open("i18n_strings.c", "w", encoding="utf-8", newline="\n") as out:
		out.write("/* Generated by tools/mkstrings.py from po/*.po, do not edit. */\n\n")
		out.write('#include "i18n.h"\n\n')
		out.write("const char *const i18n_languages[3] = {%s};\n\n" % ", ".join('"%s"' % x for x in LANGUAGES))
		out.write("const struct translation translations[] = {\n")
		for text in all_texts:
			out.write('\t{"%s", {%s}},\n' % (text, ", ".join('"%s"' % catalogs[x].get(text, "") for x in LANGUAGES)))
		out.write("};\n\nconst int translation_count = sizeof(translations) / sizeof(translations[0]);\n")


main()
