#!/bin/sh
# Builds the font of the flash window, fonts/ofg_font.c: DejaVu Sans reduced to the characters of the texts,
# which LVGL's Tiny TTF renders in the size of the window.
#
#   tools/mkfonts.sh
#
# Needs Python with fontTools (pip install fonttools) on the host, not in the image; PYTHON names another
# interpreter than python3.
set -e
cd "$(dirname "$0")/.."

# ASCII, Latin-1, Latin Extended-A, Arabic with the forms LVGL joins, typographic punctuation, check, cross and
# warning.
TEXT="20-7E,A0-17F,60C,61B,61F,621-652,660-669,67E,686,698,6A9,6AF,6CC,FB56-FB59,FB7A-FB7D,FB8A-FB8B,FB8E-FB95,FBFC-FBFF,FE70-FEFC,2013-2014,2018-201A,201C-201E,2022,2026,2713,2717,26A0"

"${PYTHON:-python3}" -m fontTools.subset tools/fonts/DejaVuSans.ttf --unicodes="$TEXT" --layout-features=kern --no-hinting \
	--desubroutinize --output-file=fonts/ofg_font.ttf
"${PYTHON:-python3}" - <<'PY'
data = open("fonts/ofg_font.ttf", "rb").read()
with open("fonts/ofg_font.c", "w", newline="\n") as out:
	out.write("/* Generated by tools/mkfonts.sh, do not edit. DejaVu Sans 2.37 reduced to the characters of the texts\n")
	out.write(" * (Bitstream Vera and Arev licenses, tools/fonts/DejaVuSans-LICENSE.txt). */\n")
	out.write("#include <stddef.h>\n\n")
	out.write("const unsigned char ofg_font_ttf[] = {\n")
	for i in range(0, len(data), 16):
		out.write("\t" + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
	out.write("};\n")
	out.write("const size_t ofg_font_ttf_size = sizeof(ofg_font_ttf);\n")
PY
rm fonts/ofg_font.ttf
