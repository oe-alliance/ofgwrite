#!/bin/sh
# Renders the fonts of the flash window into fonts/.
#
#   tools/mkfonts.sh
#
# Needs Node.js for npx lv_font_conv on the host, not in the image.
set -e
cd "$(dirname "$0")/.."

# DejaVu Sans: ASCII, Latin-1, Latin Extended-A, Arabic with the forms LVGL joins, typographic punctuation,
# check, cross and warning.
TEXT="0x20-0x7E,0xA0-0x17F,0x60C,0x61B,0x61F,0x621-0x652,0x660-0x669,0x67E,0x686,0x698,0x6A9,0x6AF,0x6CC,0xFB56-0xFB59,0xFB7A-0xFB7D,0xFB8A-0xFB8B,0xFB8E-0xFB95,0xFBFC-0xFBFF,0xFE70-0xFEFC,0x2013-0x2014,0x2018-0x201A,0x201C-0x201E,0x2022,0x2026,0x2713,0x2717,0x26A0"
# The big percentage: digits, space and percent sign.
DIGITS="0x20,0x25,0x30-0x39"

render() {
	npx -y lv_font_conv --bpp 4 --size "$2" --format lvgl --font tools/fonts/DejaVuSans.ttf -r "$3" \
		--lv-include lvgl.h --lv-font-name "$1" -o "fonts/$1.c.tmp"
	{
		echo "/* Generated by tools/mkfonts.sh, do not edit. Rendered from DejaVu Sans 2.37"
		echo " * (Bitstream Vera and Arev licenses, tools/fonts/DejaVuSans-LICENSE.txt). */"
		sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' "fonts/$1.c.tmp"  # Without the empty lines at the end.
	} > "fonts/$1.c"
	rm "fonts/$1.c.tmp"
}

for size in 14 16 20 24; do
	render "ofg_font_$size" "$size" "$TEXT"
done
for size in 44 66; do
	render "ofg_digits_$size" "$size" "$DIGITS"
done
